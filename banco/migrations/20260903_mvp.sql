BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
    versao BIGINT PRIMARY KEY,
    aplicado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS login_tokens (
    selector VARCHAR(64) PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expira_em TIMESTAMPTZ NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_uso_em TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_login_tokens_usuario ON login_tokens(usuario_id);
CREATE INDEX IF NOT EXISTS idx_login_tokens_expira ON login_tokens(expira_em);

ALTER TABLE aulas ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'publicado';
ALTER TABLE avaliacoes ADD COLUMN IF NOT EXISTS ativa BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE avaliacoes ADD COLUMN IF NOT EXISTS max_tentativas SMALLINT NOT NULL DEFAULT 3;

CREATE TABLE IF NOT EXISTS matriculas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    treinamento_id INTEGER NOT NULL REFERENCES treinamentos(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'em_andamento',
    ultima_aula_id INTEGER REFERENCES aulas(id) ON DELETE SET NULL,
    iniciado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    concluido_em TIMESTAMPTZ,
    UNIQUE (usuario_id, treinamento_id)
);

CREATE TABLE IF NOT EXISTS progresso_aulas (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    aula_id INTEGER NOT NULL REFERENCES aulas(id) ON DELETE CASCADE,
    concluida BOOLEAN NOT NULL DEFAULT TRUE,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, aula_id)
);

CREATE TABLE IF NOT EXISTS favoritos_areas (
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    area_id INTEGER NOT NULL REFERENCES areas(id) ON DELETE CASCADE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, area_id)
);

CREATE TABLE IF NOT EXISTS perguntas_avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id INTEGER NOT NULL REFERENCES avaliacoes(id) ON DELETE CASCADE,
    enunciado TEXT NOT NULL,
    ordem SMALLINT NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS alternativas_avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pergunta_id BIGINT NOT NULL REFERENCES perguntas_avaliacao(id) ON DELETE CASCADE,
    texto TEXT NOT NULL,
    correta BOOLEAN NOT NULL DEFAULT FALSE,
    ordem SMALLINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tentativas_avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    avaliacao_id INTEGER NOT NULL REFERENCES avaliacoes(id) ON DELETE CASCADE,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    nota NUMERIC(5, 2) NOT NULL DEFAULT 0,
    aprovado BOOLEAN NOT NULL DEFAULT FALSE,
    iniciado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalizado_em TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS respostas_avaliacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tentativa_id BIGINT NOT NULL REFERENCES tentativas_avaliacao(id) ON DELETE CASCADE,
    pergunta_id BIGINT NOT NULL REFERENCES perguntas_avaliacao(id) ON DELETE CASCADE,
    alternativa_id BIGINT REFERENCES alternativas_avaliacao(id) ON DELETE SET NULL,
    correta BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (tentativa_id, pergunta_id)
);

CREATE TABLE IF NOT EXISTS redefinicoes_senha (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expira_em TIMESTAMPTZ NOT NULL,
    usado_em TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tentativas_login (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador_hash CHAR(64) NOT NULL,
    ip_hash CHAR(64) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS logs_erros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    contexto VARCHAR(160) NOT NULL,
    mensagem TEXT NOT NULL,
    detalhes TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_matriculas_usuario ON matriculas(usuario_id);
CREATE INDEX IF NOT EXISTS idx_progresso_usuario ON progresso_aulas(usuario_id);
CREATE INDEX IF NOT EXISTS idx_tentativas_avaliacao_usuario ON tentativas_avaliacao(usuario_id, avaliacao_id);
CREATE INDEX IF NOT EXISTS idx_redefinicoes_expira ON redefinicoes_senha(expira_em);
CREATE INDEX IF NOT EXISTS idx_tentativas_login_data ON tentativas_login(identificador_hash, ip_hash, criado_em);
CREATE INDEX IF NOT EXISTS idx_logs_erros_data ON logs_erros(criado_em DESC);

