-- TrainHub schema for Neon PostgreSQL.
-- Execute this file once in the Neon SQL Editor before the first login.

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    senha_hash VARCHAR(255),
    google_id VARCHAR(120) UNIQUE,
    auth_provider VARCHAR(20) NOT NULL DEFAULT 'local' CHECK (auth_provider IN ('local', 'google')),
    perfil VARCHAR(20) NOT NULL DEFAULT 'instrutor' CHECK (perfil IN ('admin', 'instrutor')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS areas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    cor VARCHAR(7) NOT NULL DEFAULT '#1E40AF',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS treinamentos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id INTEGER NOT NULL REFERENCES areas(id) ON UPDATE CASCADE,
    criado_por INTEGER NOT NULL REFERENCES usuarios(id) ON UPDATE CASCADE,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    carga_horaria NUMERIC(6, 1) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'rascunho' CHECK (status IN ('rascunho', 'publicado', 'arquivado')),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS competencias (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treinamento_id INTEGER NOT NULL REFERENCES treinamentos(id) ON DELETE CASCADE ON UPDATE CASCADE,
    descricao TEXT NOT NULL,
    ordem SMALLINT NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS aulas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treinamento_id INTEGER NOT NULL REFERENCES treinamentos(id) ON DELETE CASCADE ON UPDATE CASCADE,
    titulo VARCHAR(200) NOT NULL,
    objetivo TEXT,
    conteudo TEXT,
    duracao_min INTEGER NOT NULL DEFAULT 0,
    ordem SMALLINT NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS materiais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id INTEGER NOT NULL REFERENCES aulas(id) ON DELETE CASCADE ON UPDATE CASCADE,
    nome VARCHAR(200) NOT NULL,
    arquivo VARCHAR(300) NOT NULL,
    tipo VARCHAR(10) NOT NULL,
    tamanho_kb INTEGER NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS avaliacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    treinamento_id INTEGER NOT NULL REFERENCES treinamentos(id) ON DELETE CASCADE ON UPDATE CASCADE,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    arquivo VARCHAR(300),
    nota_minima NUMERIC(5, 2) NOT NULL DEFAULT 6.00,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessoes (
    id VARCHAR(128) PRIMARY KEY,
    dados TEXT NOT NULL,
    expira_em TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_treinamentos_area ON treinamentos(area_id);
CREATE INDEX IF NOT EXISTS idx_treinamentos_status ON treinamentos(status);
CREATE UNIQUE INDEX IF NOT EXISTS idx_treinamentos_titulo_unique ON treinamentos(titulo);
CREATE UNIQUE INDEX IF NOT EXISTS idx_areas_nome_unique ON areas(nome);
CREATE INDEX IF NOT EXISTS idx_aulas_treinamento ON aulas(treinamento_id);
CREATE INDEX IF NOT EXISTS idx_materiais_aula ON materiais(aula_id);
CREATE INDEX IF NOT EXISTS idx_sessoes_expira_em ON sessoes(expira_em);
CREATE TABLE IF NOT EXISTS atividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
    acao VARCHAR(120) NOT NULL,
    descricao TEXT NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pedidos_suporte (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    mensagem TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'em_atendimento', 'resolvido')),
    resposta TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_atividades_criado_em ON atividades(criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_suporte_status ON pedidos_suporte(status);

