function exigirLogin(): void
{
    if (!usuarioLogado()) {
        redirecionar('index.php');
    }

    global $pdo;
    try {
        $stmt = $pdo->prepare('SELECT id, nome, email, perfil, ativo FROM usuarios WHERE id = ? LIMIT 1');
        $stmt->execute([(int) $_SESSION['usuario_id']]);
        $usuario = $stmt->fetch();
        $ativo = $usuario && in_array($usuario['ativo'], [true, 1, '1', 't', 'true'], true);
        if (!$usuario || !$ativo) {
            $bloqueado = $usuario ?: null;
            $_SESSION = [];
            if ($bloqueado) {
                $_SESSION['usuario_bloqueado_id'] = (int) $bloqueado['id'];
                $_SESSION['usuario_bloqueado_nome'] = (string) $bloqueado['nome'];
                $_SESSION['usuario_bloqueado_email'] = (string) ($bloqueado['email'] ?? '');
                redirecionar('index.php?bloqueado=1');
            }
            redirecionar('index.php');
        }
        $_SESSION['usuario_nome'] = (string) $usuario['nome'];
        $_SESSION['usuario_email'] = (string) ($usuario['email'] ?? '');
        $_SESSION['usuario_perfil'] = (string) $usuario['perfil'];
    } catch (Throwable $e) {
        error_log('TrainHub session validation failed: ' . $e->getMessage());
        redirecionar('index.php?erro=erro_interno');
    }
}

