function revogarLoginLembrado(): void
{
    global $pdo;
    $valor = (string) ($_COOKIE['trainhub_remember'] ?? '');
    $partes = explode('.', $valor, 2);
    if (count($partes) === 2 && preg_match('/^[a-f0-9]{32}$/', $partes[0])) {
        try {
            $stmt = $pdo->prepare('DELETE FROM login_tokens WHERE selector = ?');
            $stmt->execute([$partes[0]]);
        } catch (Throwable $e) {
            error_log('TrainHub remember token revoke failed: ' . $e->getMessage());
        }
    }
    cookieLoginLembrado(null, time() - 3600);
    unset($_COOKIE['trainhub_remember']);
}

function criarLoginLembrado(int $usuarioId): void
{
    global $pdo;
    revogarLoginLembrado();
    $selector = bin2hex(random_bytes(16));
    $validator = bin2hex(random_bytes(32));
    $expiraEm = date('Y-m-d H:i:sP', time() + (60 * 60 * 24 * 30));
    $stmt = $pdo->prepare(
        'INSERT INTO login_tokens (selector, usuario_id, token_hash, expira_em) VALUES (?, ?, ?, ?)'
    );
    $stmt->execute([$selector, $usuarioId, hash('sha256', $validator), $expiraEm]);
    cookieLoginLembrado($selector . '.' . $validator, time() + (60 * 60 * 24 * 30));
}

function restaurarLoginLembrado(): void
{
    if (usuarioLogado()) {
        return;
    }

    global $pdo;
    $valor = (string) ($_COOKIE['trainhub_remember'] ?? '');
    $partes = explode('.', $valor, 2);
    if (count($partes) !== 2 || !preg_match('/^[a-f0-9]{32}$/', $partes[0]) || !preg_match('/^[a-f0-9]{64}$/', $partes[1])) {
        if ($valor !== '') {
            cookieLoginLembrado(null, time() - 3600);
        }
        return;
    }

    try {
        $stmt = $pdo->prepare(
            'SELECT u.id, u.nome, u.email, u.perfil, u.ativo FROM login_tokens l JOIN usuarios u ON u.id = l.usuario_id WHERE l.selector = ? AND l.token_hash = ? AND l.expira_em > CURRENT_TIMESTAMP LIMIT 1'
        );
        $stmt->execute([$partes[0], hash('sha256', $partes[1])]);
        $usuario = $stmt->fetch();
        if (!$usuario) {
            revogarLoginLembrado();
            return;
        }

        if (!valorBooleano($usuario['ativo'])) {
            revogarLoginLembrado();
            $_SESSION['usuario_bloqueado_id'] = (int) $usuario['id'];
            $_SESSION['usuario_bloqueado_nome'] = (string) $usuario['nome'];
            $_SESSION['usuario_bloqueado_email'] = (string) ($usuario['email'] ?? '');
            return;
        }

        session_regenerate_id(true);
        $_SESSION['usuario_id'] = (int) $usuario['id'];
        $_SESSION['usuario_nome'] = (string) $usuario['nome'];
        $_SESSION['usuario_email'] = (string) ($usuario['email'] ?? '');
        $_SESSION['usuario_perfil'] = (string) $usuario['perfil'];
        $_SESSION['logado'] = true;

        $novoValidator = bin2hex(random_bytes(32));
        $novaExpiracao = date('Y-m-d H:i:sP', time() + (60 * 60 * 24 * 30));
        $stmt = $pdo->prepare('UPDATE login_tokens SET token_hash = ?, expira_em = ?, ultimo_uso_em = CURRENT_TIMESTAMP WHERE selector = ?');
        $stmt->execute([hash('sha256', $novoValidator), $novaExpiracao, $partes[0]]);
        cookieLoginLembrado($partes[0] . '.' . $novoValidator, time() + (60 * 60 * 24 * 30));
    } catch (Throwable $e) {
        error_log('TrainHub remember token restore failed: ' . $e->getMessage());
        revogarLoginLembrado();
    }
}

