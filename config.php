function bancoPostgres(PDO $pdo): bool
{
    return $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql';
}

function inserirComId(PDO $pdo, string $sql, array $parametros): int
{
    if (bancoPostgres($pdo)) {
        $stmt = $pdo->prepare(rtrim($sql, " \t\n\r\0\x0B;") . ' RETURNING id');
        $stmt->execute($parametros);
        return (int) $stmt->fetchColumn();
    }
    $stmt = $pdo->prepare($sql);
    $stmt->execute($parametros);
    return (int) $pdo->lastInsertId();
}

function registrarAtividade(PDO $pdo, int $usuarioId, string $acao, string $descricao): void
{
    $stmt = $pdo->prepare('INSERT INTO atividades (usuario_id, acao, descricao) VALUES (?, ?, ?)');
    $stmt->execute([$usuarioId, mb_substr($acao, 0, 120), $descricao]);
}

function registrarErro(PDO $pdo, string $contexto, Throwable $erro): void
{
    error_log('TrainHub ' . $contexto . ': ' . $erro->getMessage());
    try {
        $stmt = $pdo->prepare('INSERT INTO logs_erros (usuario_id, contexto, mensagem, detalhes) VALUES (?, ?, ?, ?)');
        $stmt->execute([
            isset($_SESSION['usuario_id']) ? (int) $_SESSION['usuario_id'] : null,
            mb_substr($contexto, 0, 160),
            mb_substr($erro->getMessage(), 0, 2000),
            mb_substr($erro->getTraceAsString(), 0, 8000),
        ]);
    } catch (Throwable) {
        // O log do PHP acima continua disponível mesmo se o banco falhar.
    }
}

function garantirMatriculasPublicadas(PDO $pdo, int $usuarioId): void
{
    if ($usuarioId < 1) {
        return;
    }
    if (bancoPostgres($pdo)) {
        $stmt = $pdo->prepare(
            "INSERT INTO matriculas (usuario_id, treinamento_id)
             SELECT ?, t.id FROM treinamentos t WHERE t.status = 'publicado'
             ON CONFLICT (usuario_id, treinamento_id) DO NOTHING"
        );
    } else {
        $stmt = $pdo->prepare(
            "INSERT IGNORE INTO matriculas (usuario_id, treinamento_id)
             SELECT ?, t.id FROM treinamentos t WHERE t.status = 'publicado'"
        );
    }
    $stmt->execute([$usuarioId]);
}

final class TrainHubSessionHandler implements SessionHandlerInterface
{
    public function __construct(private PDO $pdo) {}

    public function open(string $path, string $name): bool { return true; }
    public function close(): bool { return true; }

    public function read(string $id): string|false
    {
        $stmt = $this->pdo->prepare(
            'SELECT dados FROM sessoes WHERE id = ? AND expira_em > CURRENT_TIMESTAMP'
        );
        $stmt->execute([$id]);
        $dados = $stmt->fetchColumn();
        return $dados === false ? '' : (string) $dados;
    }

    public function write(string $id, string $data): bool
    {
        $seconds = max(300, (int) ini_get('session.gc_maxlifetime'));
        $stmt = $this->pdo->prepare(
            'INSERT INTO sessoes (id, dados, expira_em) VALUES (?, ?, CURRENT_TIMESTAMP + (? * INTERVAL \'1 second\')) '
            . 'ON CONFLICT (id) DO UPDATE SET dados = EXCLUDED.dados, expira_em = EXCLUDED.expira_em'
        );
        return $stmt->execute([$id, $data, $seconds]);
    }

    public function destroy(string $id): bool
    {
        $stmt = $this->pdo->prepare('DELETE FROM sessoes WHERE id = ?');
        return $stmt->execute([$id]);
    }

    public function gc(int $max_lifetime): int|false
    {
        return $this->pdo->exec('DELETE FROM sessoes WHERE expira_em <= CURRENT_TIMESTAMP');
    }
}

